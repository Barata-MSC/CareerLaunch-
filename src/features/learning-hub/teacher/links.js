function topicReference(topic, title) {
  return ref(EDUTOPIA, title, TOPIC_URLS[topic], EDUTOPIA);
}

function linksFor(prefix, topics) {
  return Object.fromEntries(
    topics.map(([topic, title], index) => [
      `${prefix}-${index + 1}`,
      { references: [topicReference(topic, title)], referencesHeading: 'Further reading' },
    ]),
  );
}

