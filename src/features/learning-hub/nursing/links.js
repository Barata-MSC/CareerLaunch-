function linksFor(prefix, sourceKeys) {
  return Object.fromEntries(
    sourceKeys.map((sourceKey, index) => [
      `${prefix}-${index + 1}`,
      {
        references: [SOURCES[sourceKey]],
        referencesHeading: 'Further reading',
      },
    ]),
  );
}

